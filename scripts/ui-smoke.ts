import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { existsSync, mkdirSync, mkdtempSync, rmSync } from 'node:fs';
import { spawn } from 'node:child_process';
import { createServer } from 'node:net';
import os from 'node:os';
import path from 'node:path';
const probe=createServer();await new Promise<void>(resolve=>probe.listen(0,'127.0.0.1',resolve));const port=(probe.address() as {port:number}).port;await new Promise<void>(resolve=>probe.close(()=>resolve()));
const temporary=mkdtempSync(path.join(os.tmpdir(),'daylight-ui-'));
const server=spawn(process.execPath,['--import','tsx','server/index.ts'],{env:{...process.env,NODE_ENV:'production',HOST:'127.0.0.1',PORT:String(port),DATA_DIR:temporary,APP_PASSWORD:'',DAYLIGHT_OPENAI_KEY:'',OPENAI_API_KEY:''},stdio:['ignore','pipe','pipe']});
let serverOutput='';server.stdout.on('data',b=>{serverOutput+=b.toString();});server.stderr.on('data',b=>{serverOutput+=b.toString();});
const base=`http://127.0.0.1:${port}`;
for(let i=0;i<100;i++){if(serverOutput.includes('Daylight listening'))break;if(server.exitCode!==null)throw new Error('Test server failed: '+serverOutput);await new Promise(r=>setTimeout(r,100));}
const artifacts=process.env.TEST_ARTIFACTS||'/tmp/daylight-review';mkdirSync(artifacts,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE_PATH||(existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined)});
const context=await browser.newContext({viewport:{width:1440,height:1024},deviceScaleFactor:1});
const page=await context.newPage();const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
try {
 await page.goto(base);
 await page.getByRole('button',{name:'体验今日筛选'}).click();
 await page.getByRole('heading',{name:'今日筛选，已为你整理。'}).waitFor({timeout:30000});
 const state=await (await page.request.get(base+'/api/state?mode=demo')).json();
 assert.equal(state.runs[0].status,'complete');assert.equal(state.jobs.length,6);assert.ok(state.jobs.every((j:any)=>j.status!=='submitted'));assert.ok(state.jobs.some((j:any)=>j.status==='skipped'));assert.ok(state.jobs.some((j:any)=>j.status==='needs_manual'));assert.ok(state.jobs.some((j:any)=>j.match?.score>=70));assert.ok(state.resumes.some((r:any)=>r.parentId));
 await page.screenshot({path:path.join(artifacts,'desktop.png'),fullPage:true});
 await page.getByRole('button',{name:'Investment Analyst Intern',exact:true}).click();
 await page.getByRole('heading',{name:'原始简历逐一比较'}).waitFor();
 assert.equal(await page.locator('.comparison-row').count(),2);
 await page.getByRole('button',{name:'关闭',exact:true}).click();
 await page.getByRole('button',{name:/简历工作室/}).click();
 await page.locator('.resume-card').filter({hasText:'Northstar Capital'}).click();
 await page.getByRole('dialog',{name:'简历版本 · 对照检查'}).waitFor();
 assert.ok((await page.locator('.highlight-excerpts p').count())>0);
 const download=page.waitForEvent('download');await page.getByRole('link',{name:'下载 DOCX'}).click();assert.match((await download).suggestedFilename(),/\.docx$/);
 await page.getByRole('button',{name:'关闭',exact:true}).click();
 await page.getByRole('button',{name:'活动日志',exact:true}).click();
 assert.ok(await page.locator('.timeline-item').count()>10);
 const excel=page.waitForEvent('download');await page.getByRole('link',{name:'导出 Excel'}).click();assert.match((await excel).suggestedFilename(),/^daylight-demo-.*\.xlsx$/);
 await page.getByRole('button',{name:'连接与设置',exact:true}).click();
 await page.getByRole('heading',{name:'连接你的求职工具'}).waitFor();
 const input=page.getByLabel('岗位关键词（可留空，由不同简历版本匹配）');const previous=await input.inputValue();await input.fill('');await page.getByRole('button',{name:'保存所有设置'}).click();await page.getByRole('status').filter({hasText:'设置已保存'}).waitFor();await input.fill(previous);
 await page.getByRole('button',{name:'真实',exact:true}).click();
 await page.getByRole('heading',{name:'连接你的求职工具'}).waitFor();
 const live=await (await page.request.get(base+'/api/state?mode=live')).json();assert.equal(live.jobs.length,0);assert.equal(live.resumes.length,0);
 await page.getByRole('button',{name:'工作台',exact:true}).click();
 await page.getByRole('heading',{name:'你的下一步，从这里开始'}).waitFor();
 await page.getByRole('button',{name:'演示',exact:true}).click();
 await page.getByRole('heading',{name:'今日筛选，已为你整理。'}).waitFor();
 if(await page.getByRole('button',{name:'关闭提示'}).count())await page.getByRole('button',{name:'关闭提示'}).click();
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(artifacts,'mobile.png'),fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 assert.deepEqual(errors,[]);console.log('PASS: demo workflow, multi-resume comparisons, resume review/DOCX download, daily logs/XLSX download, settings persistence, demo/live isolation, mobile layout; no browser exceptions.');
}finally{await browser.close();server.kill('SIGTERM');await new Promise<void>(resolve=>server.once('exit',()=>resolve()));rmSync(temporary,{recursive:true,force:true});}
